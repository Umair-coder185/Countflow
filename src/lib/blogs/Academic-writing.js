    <blockquote>
      Remote work can improve productivity in roles where employees have
      sufficient autonomy and appropriate digital resources. However, the
      effect should not be treated as universal because productivity measures
      vary across occupations and research designs. A stronger workplace policy
      would therefore match remote-working arrangements to the requirements of
      specific roles rather than assume one model will suit every employee.
    </blockquote>

